/**
 * API 失敗・不正レスポンス・空返答など、応答を返せないときにチャットに出す定型文。
 * 毎回同じ文言にならないようランダムに選ぶ。
 */
const CHAT_UNAVAILABLE_TEMPLATES = [
	"すみません、いまはうまく回答を返せませんでした。お急ぎでしたら、メールや SNS から気軽に連絡してください。",
	"申し訳ありません、応答を返せませんでした。必要であれば、このサイトのメールや SNS から直接ご連絡いただけるとうれしいです。",
	"ごめんなさい、今は回答をお届けできませんでした。急ぎのご相談は、メールか SNS で声をかけてもらえると助かります。",
	"すみません、一時的に応答できませんでした。時間をおいて試すか、メールや SNS から連絡してください。",
	"申し訳ありません、回答を生成できませんでした。もしよければ、このサイトに載せているメールや SNS からご連絡ください。",
	"ごめんなさい、いまはメッセージを返せませんでした。相談やお問い合わせは、メールや SNS 経由でも大丈夫です。",
	"すみません、API の利用上限や一時的な混雑で回答を返せない可能性があります。お急ぎなら、メールや SNS から直接ご連絡ください。",
	"申し訳ありません、現在は API 側の上限に達しているか、一時的に負荷が高い可能性があります。急ぎの場合は、メールや SNS からご連絡いただけるとうれしいです。",
] as const;

export function getRandomChatUnavailableReply(): string {
	const index = Math.floor(Math.random() * CHAT_UNAVAILABLE_TEMPLATES.length);
	return CHAT_UNAVAILABLE_TEMPLATES[index]!;
}
